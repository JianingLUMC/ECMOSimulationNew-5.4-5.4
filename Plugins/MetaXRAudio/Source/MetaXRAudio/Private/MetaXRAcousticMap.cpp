void UMetaXRAcousticMap::Activate(bool bReset) {
  if (CachedMap == nullptr) {
    return;
  }

  ovrResult Result;
  Result = OVRA_CALL(ovrAudio_AudioSceneIRSetEnabled)(CachedMap, true);
  if (Result != ovrSuccess) {
    UE_LOG(LogAudio, Warning, TEXT("Failed to Set Acoustic Map %p to enabled"), CachedMap);
  } else {
    UE_LOG(LogAudio, Log, TEXT("Set Acoustic Map %p to enabled"), CachedMap);
  }
}

void UMetaXRAcousticMap::Deactivate() {
  ovrResult Result;
  Result = OVRA_CALL(ovrAudio_AudioSceneIRSetEnabled)(CachedMap, false);
  if (Result != ovrSuccess) {
    UE_LOG(LogAudio, Warning, TEXT("Failed to Set Acoustic Map %p to disabled"), CachedMap);
  } else {
    UE_LOG(LogAudio, Log, TEXT("Set Acoustic Map %p to disabed"), CachedMap);
  }
}

// This function ensures a map point is converted to the right format before storing
void UMetaXRAcousticMap::AddPoint(FVector NewPoint) {
  // ovrAudio will internally apply the Acoustic Map transform, so we need to undo that here
  FTransform Transform = GetComponentTransform().Inverse();
  FVector TransformedPoint = Transform.TransformPosition(NewPoint);

  // New point will be in UE axis coordinates and we want the points to be in ovrAudio axis so we can directly upload them
  CachedPoints.Add(MetaXRAudioUtilities::ToOVRVector(TransformedPoint));
}

FVector UMetaXRAcousticMap::GetNewPointForRay(FVector RayOrigin, FVector RayDirection) {
  float DefaultDistance = 400.0f; // How far away to place a point if the ray hits nothing
  float TraceDistance = 60000.0f; // How far away to fire the ray trace before giving up
  FVector EndPosition = RayOrigin + (RayDirection * TraceDistance); // The point at the end of our longest possible ray

  // Try to perform raytracing to find a point in front of the camera that is not blocked by geometry.
  FVector NewPointPosition;
  UWorld* World = GetWorld();
  if (World != nullptr) {
    // Setup variables for unreal's raytracing function
    FHitResult HitResult;
    FCollisionObjectQueryParams ObjectTypes;
    ObjectTypes.AddObjectTypesToQuery(ECC_WorldStatic);
    ObjectTypes.AddObjectTypesToQuery(ECC_WorldDynamic);
    FCollisionQueryParams QueryParams;

    // Perform a single raytrace which will tell us the first blocking hit.
    bool HitFound = World->LineTraceSingleByObjectType(HitResult, RayOrigin, EndPosition, ObjectTypes, QueryParams);
    if (HitResult.bBlockingHit && IsValid(HitResult.GetActor())) {
      // Place the point slightly away from the hit point to avoid placing points on walls.
      float bias = 300.0f;
      NewPointPosition = RayOrigin + (RayDirection * FMath::Max(HitResult.Distance - bias, 0.0f));

      if (bNoFloating == false) {
        return NewPointPosition;
      }

      // Trace two rays down and up to place the point at the right height.
      FVector DownRayEndPosition = NewPointPosition + (GravityVector.GetUnsafeNormal() * TraceDistance);
      if (World->LineTraceSingleByObjectType(HitResult, NewPointPosition, DownRayEndPosition, ObjectTypes, QueryParams)) {
        float downDistance = HitResult.Distance;
        float targetHeight = NewPointPosition.Z;

        if (downDistance > MaxHeight) {
          targetHeight = HeadHeight;
        } else if (downDistance < HeadHeight) {
          FVector UpRayEndPosition = NewPointPosition - (GravityVector.GetUnsafeNormal() * TraceDistance);
          if (World->LineTraceSingleByObjectType(HitResult, NewPointPosition, UpRayEndPosition, ObjectTypes, QueryParams)) {
            // Move point so that it is either at head height or is at the floor/ceiling midpoint if that is less.
            float midHeight = 0.5f * (downDistance + HitResult.Distance);
            targetHeight = FMath::Min(HeadHeight, midHeight);
          }
        }

        // height adjustment
        NewPointPosition += GravityVector * (downDistance - targetHeight);
      }
      return NewPointPosition;
    } else {
      // Facing empty space, place the point slightly in front of the camera.
      return RayOrigin + (RayDirection * DefaultDistance);
    }
  }

  // Place slightly in front of camera as fallback if cannot raytrace or we didn't hit anything
  return RayOrigin + (RayDirection * DefaultDistance);
}

FMetaXRAcousticMapSceneProxy::FMetaXRAcousticMapSceneProxy(const UPrimitiveComponent* InComponent) : FDebugRenderSceneProxy(InComponent) {
  AcousticMapComponent = Cast<UMetaXRAcousticMap>(InComponent);
  for (uint32_t Stack = 0; Stack <= NumStacks; ++Stack) {
    for (uint32_t Slice = 0; Slice <= NumSlices; ++Slice) {
      const float XSegment = static_cast<float>(Slice) / static_cast<float>(NumSlices);
      const float YSegment = static_cast<float>(Stack) / static_cast<float>(NumStacks);
      const float XPos = FMath::Cos(XSegment * 2 * PI) * FMath::Sin(YSegment * PI);
      const float YPos = FMath::Cos(YSegment * PI);
      const float ZPos = FMath::Sin(XSegment * 2 * PI) * FMath::Sin(YSegment * PI);

      FDynamicMeshVertex Vertex;
      Vertex.Position = FVector3f(XPos, YPos, ZPos);
      Vertices.Add(Vertex);
    }
  }

  for (uint32_t Stack = 0; Stack < NumStacks; ++Stack) {
    for (uint32_t Slice = 0; Slice < NumSlices; ++Slice) {
      Indices.Add((Stack + 1) * (NumSlices + 1) + Slice);
      Indices.Add(Stack * (NumSlices + 1) + Slice);
      Indices.Add(Stack * (NumSlices + 1) + Slice + 1);

      Indices.Add((Stack + 1) * (NumSlices + 1) + Slice);
      Indices.Add(Stack * (NumSlices + 1) + Slice + 1);
      Indices.Add((Stack + 1) * (NumSlices + 1) + Slice + 1);
    }
  }
}

FPrimitiveViewRelevance FMetaXRAcousticMapSceneProxy::GetViewRelevance(const FSceneView* View) const {
  IConsoleVariable* MetaXRAudioGizmoCVAR = IConsoleManager::Get().FindConsoleVariable(TEXT("MetaXRAudioGizmos"));
  bool bVisible = MetaXRAudioGizmoCVAR->GetInt() != 0;
  FPrimitiveViewRelevance Result;
  Result.bDrawRelevance = bVisible;
  Result.bDynamicRelevance = true;
  return Result;
}

void FMetaXRAcousticMapSceneProxy::GetDynamicMeshElements(
    const TArray<const FSceneView*>& Views,
    const FSceneViewFamily& ViewFamily,
    uint32 VisibilityMap,
    FMeshElementCollector& Collector) const {
  FColoredMaterialRenderProxy* RedMaterial =
      new FColoredMaterialRenderProxy(GEngine->LevelColorationUnlitMaterial->GetRenderProxy(), FLinearColor::Red);
  FColoredMaterialRenderProxy* YellowMaterial =
      new FColoredMaterialRenderProxy(GEngine->LevelColorationUnlitMaterial->GetRenderProxy(), FLinearColor::Yellow);
  Collector.RegisterOneFrameMaterialProxy(RedMaterial);
  Collector.RegisterOneFrameMaterialProxy(YellowMaterial);

  for (int32 ViewIndex = 0; ViewIndex < Views.Num(); ViewIndex++) {
    if (VisibilityMap & (1 << ViewIndex)) {
      const FSceneView* View = Views[ViewIndex];
      for (int32 i = 0; i < AcousticMapComponent->CachedPoints.Num(); i++) {
        // Cached points are stored in ovrAudio axis and haven't applied their Acoustic Map Transform
        FTransform Transform = AcousticMapComponent->GetComponentTransform();
        const FVector& Point = Transform.TransformPosition(MetaXRAudioUtilities::ToUEVector(AcousticMapComponent->CachedPoints[i]));

        // Create a dynamic mesh builder
        FDynamicMeshBuilder MeshBuilder(View->GetFeatureLevel());
        MeshBuilder.AddVertices(Vertices);
        MeshBuilder.AddTriangles(Indices);

        // Add mesh to the collector
        FTransform SphereTransform(FQuat::Identity, Point, FVector(META_XR_AUDIO_MAP_SPHERE_RADIUS));
        MeshBuilder.GetMesh(
            SphereTransform.ToMatrixWithScale(),
            (AcousticMapComponent->SelectedPointIndex == i) ? RedMaterial : YellowMaterial,
            SDPG_World,
            true,
            false,
            false,
            ViewIndex,
            Collector);
      }
    }
  }
}
