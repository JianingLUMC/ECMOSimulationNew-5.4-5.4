// This function tells the renderer where the Map Points are so it can only render it while in frame
FBoxSphereBounds UMetaXRAcousticMap::CalcBounds(const FTransform& LocalToWorld) const {
  TArray<FVector> Points;
  Points.SetNum(CachedPoints.Num());
  for (int32 i = 0; i < CachedPoints.Num(); i++) {
    // Cached points are stored in ovrAudio axis and haven't applied their Acoustic Map Transform
    FTransform Transform = GetComponentTransform();
    Points.Add(Transform.TransformPosition(MetaXRAudioUtilities::ToUEVector(CachedPoints[i])));
  }

  // This constructor will compute a bounding box based on our points
  if (!CachedPoints.Num()) {
    FBoxSphereBounds EmptyBounds;
    return EmptyBounds;
  }
  FBoxSphereBounds MapBounds(&Points[0], Points.Num());
  return MapBounds;
}

void UMetaXRAcousticMap::TickComponent(float DeltaTime, enum ELevelTick TickType, FActorComponentTickFunction* ThisTickFunction) {
  Super::TickComponent(DeltaTime, TickType, ThisTickFunction);

#if WITH_EDITOR
  if (bComputing) {
    // Try to get rid of the thread if the user cancelled
    if (bComputeCanceled && !MappingTask->IsDone()) {
      MappingTask->TryAbandonTask();
    }

    // Poll to see if the async compute was finished.
    if (MappingTask->IsDone() || bComputeFinished) {
      bool wasCancelled = bComputeCanceled;

      // Do final cleanup on the main thread after computing the IR.
      FinishCompute();

      if (wasCancelled) {
        UE_LOG(LogAudio, Warning, TEXT("Attempting to load previous bake %s"), *FilePath);
        DestroyInternal();
        StartInternal();
      }
    }
  }
#endif

  FTransform Transform = GetComponentTransform();
  if (!Transform.Equals(PreviousTransform)) {
    ApplyTransform();
  }
}

