void UMetaXRAcousticGeometry::UpdateGizmoMesh(ovrAudioGeometry GeometryHandle) {
  if (GeometryHandle == nullptr) {
    UE_LOG(LogAudio, Warning, TEXT("Unable to update gizmo: Geometry not loaded."));
  }

  uint32_t NumVertices, NumTriangles = 0;
  ovrResult Result = OVRA_CALL(ovrAudio_AudioGeometryGetSimplifiedMesh)(GeometryHandle, nullptr, &NumVertices, nullptr, &NumTriangles);

  if (Result != ovrSuccess) {
    UE_LOG(LogAudio, Warning, TEXT("Failed getting simplified mesh from the audio propagation sub-system!"));
  } else {
    SimplifiedVertices.SetNum(NumVertices);
    SimplifiedIndices.SetNum(NumTriangles * 3);

    TArray<FVector3f> VertexArray;
    VertexArray.SetNum(NumVertices);

    Result = OVRA_CALL(ovrAudio_AudioGeometryGetSimplifiedMesh)(
        GeometryHandle, (float*)VertexArray.GetData(), &NumVertices, SimplifiedIndices.GetData(), &NumTriangles);
    if (Result != ovrSuccess) {
      UE_LOG(LogAudio, Warning, TEXT("Failed getting simplified mesh from the audio propagation sub-system!"));
    } else {
      for (size_t i = 0; i < NumVertices; i++) {
        SimplifiedVertices[i] = FDynamicMeshVertex(MetaXRAudioUtilities::ToUEVector3f(VertexArray[i]));
      }
    }
  }

  IPlatformFile& PlatformFile = FPlatformFileManager::Get().GetPlatformFile();
  FString FullFilePath = FPaths::ProjectContentDir() / FilePath;
  if (PlatformFile.FileExists(*FullFilePath)) {
    IFileHandle* FileHandle = PlatformFile.OpenRead(*FullFilePath);
    if (FileHandle) {
      DataSize = FileHandle->Size();
    }
    delete FileHandle;
  }
}

