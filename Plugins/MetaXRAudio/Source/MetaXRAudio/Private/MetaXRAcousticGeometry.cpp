bool UMetaXRAcousticGeometry::ReadFile() {
  if (FilePath.IsEmpty()) {
    UE_LOG(LogAudio, Warning, TEXT("No geometry file path provided!"));
    return false;
  }

  if (MetaXRAudioUtilities::PlayModeActive(GetWorld())) {
    LoadGeometryAsync();
  } else {
    FString FullFilePath = FPaths::ProjectContentDir() / FilePath;
    if (!FPaths::FileExists(FullFilePath)) {
      UE_LOG(LogAudio, Warning, TEXT("Audio geometry file not found: %s"), *FullFilePath);
      return false;
    }

    // Read the file data into a byte array
    ovrResult Result = OVRA_CALL(ovrAudio_AudioGeometryReadMeshFile)(OvrGeometry, TCHAR_TO_UTF8(*FullFilePath));
    if (Result != ovrSuccess) {
      UE_LOG(LogAudio, Warning, TEXT("Unable to read audio geometry from file: %s"), *FullFilePath);
      return false;
    } else {
      UE_LOG(LogAudio, Log, TEXT("Successfully read geometry from file: %s"), *FullFilePath);
    }

    Result = OVRA_CALL(ovrAudio_AudioGeometrySetObjectFlag)(OvrGeometry, ovrAudioObjectFlag_Enabled, true);
    Result = OVRA_CALL(ovrAudio_AudioGeometrySetObjectFlag)(OvrGeometry, ovrAudioObjectFlag_Static, IsStatic());
  }

#if WITH_EDITOR
  UpdateGizmoMesh();
#endif
  return true;
}

bool UMetaXRAcousticGeometry::WriteFile() {
  // Create a temporary geometry.
  ovrAudioGeometry tempGeometryHandle;
  ovrResult Result = OVRA_CALL(ovrAudio_CreateAudioGeometry)(CachedContext, &tempGeometryHandle);
  if (Result != ovrSuccess) {
    UE_LOG(LogAudio, Warning, TEXT("Unable to create temp audio geometry"));
    return false;
  } else {
    UE_LOG(LogAudio, Log, TEXT("Created new temporary geometry handle %p"), tempGeometryHandle);
  }

  // Upload the mesh geometry and then write the result to disk
  bool Succeeded = false;
  if (UploadMesh(tempGeometryHandle)) {
    if (WriteFileInternal(tempGeometryHandle)) {
      Succeeded = true;
    }
  }

  // Destroy the geometry.
  UE_LOG(LogAudio, Log, TEXT("Destroying temporary geometry handle %p"), tempGeometryHandle);
  if (OVRA_CALL(ovrAudio_DestroyAudioGeometry)(tempGeometryHandle) != ovrSuccess) {
    UE_LOG(LogAudio, Warning, TEXT("Failed to destroy temp geometry handle"));
    Succeeded = false;
  }

  return Succeeded;
}

bool UMetaXRAcousticGeometry::WriteFileInternal(ovrAudioGeometry GeometryHandle) {
  // Setup the filepaths for the output file
#if WITH_EDITOR
  GenerateFileNameIfEmpty();
#endif
  FString FullFilePath = FPaths::ProjectContentDir() / FilePath;
#if WITH_EDITOR
  MetaXRAudioUtilities::CreateMetaXRAcousticContentDirectory(FPaths::GetPath(FilePath));
#endif

  // Write the mesh to a file.
  ovrResult Result = OVRA_CALL(ovrAudio_AudioGeometryWriteMeshFile)(GeometryHandle, TCHAR_TO_ANSI(*FullFilePath));
  if (Result != ovrSuccess) {
    UE_LOG(LogAudio, Warning, TEXT("Unable to save geometry to file"));
  } else {
    UE_LOG(LogAudio, Display, TEXT("Successfully wrote geometry to file: %s"), *FullFilePath);
  }

#if WITH_EDITOR
  UpdateGizmoMesh(GeometryHandle);
#endif

  if (!bFileEnabled) {
    UE_LOG(LogAudio, Warning, TEXT("File Successfully written but File Enabled is off, turn it on to use file"));
  }

  IPlatformFile& PlatformFile = FPlatformFileManager::Get().GetPlatformFile();
  if (PlatformFile.FileExists(*FullFilePath)) {
    IFileHandle* FileHandle = PlatformFile.OpenRead(*FullFilePath);
    if (FileHandle) {
      DataSize = FileHandle->Size();
    }
    delete FileHandle;
  }

  return true;
}

void UMetaXRAcousticGeometry::LoadGeometryAsync() {
  FString FullFilePath = FPaths::ProjectContentDir() / FilePath;
#if WITH_EDITOR
  if (!FPaths::FileExists(FullFilePath)) {
    UE_LOG(LogAudio, Warning, TEXT("Audio geometry file not found: %s"), *FullFilePath);
    return;
  }
#endif

  // Read the file data into a byte array
  TArray<uint8> FileData;
  if (!FFileHelper::LoadFileToArray(FileData, *FullFilePath)) {
    UE_LOG(LogAudio, Warning, TEXT("Failed to load audio geometry file: %s"), *FullFilePath);
    return;
  }

  ovrResult Result = OVRA_CALL(ovrAudio_AudioGeometryReadMeshMemory)(OvrGeometry, (const int8_t*)FileData.GetData(), FileData.Num());
  if (Result != ovrSuccess) {
    UE_LOG(LogAudio, Warning, TEXT("Unable to read audio geometry from memory: %s"), *FullFilePath);
    return;
  } else {
    UE_LOG(LogAudio, Log, TEXT("Successfully read audio geometry from memory: %s"), *FullFilePath);
  }

  Result = OVRA_CALL(ovrAudio_AudioGeometrySetObjectFlag)(OvrGeometry, ovrAudioObjectFlag_Enabled, true);
  ApplyTransform();
  Result = OVRA_CALL(ovrAudio_AudioGeometrySetObjectFlag)(OvrGeometry, ovrAudioObjectFlag_Static, IsStatic());

#if WITH_EDITOR
  UpdateGizmoMesh();
#endif
}

